        private void BindGridView()
        {
            string brand_id = DDL_ProductBrand.SelectedValue.ToString();
            lbl_DDL_ProductBrand_Value.Text = brand_id;
            string connStr = ConfigurationManager.ConnectionStrings["DbConn"].ConnectionString;
            using (SqlConnection conn = new SqlConnection(connStr))
            {
                using (SqlCommand cmd = new SqlCommand("GetBrandSKUs", conn))
                {
                    cmd.CommandType = CommandType.StoredProcedure;
                    cmd.Parameters.AddWithValue("@BrandId", brand_id);
                    conn.Open();
                    SqlDataAdapter sda = new SqlDataAdapter(cmd);
                    DataTable dt = new DataTable();
                    sda.Fill(dt);
                    GridView1.DataSource = dt;
                    GridView1.DataBind();
                }
            }
        }


        protected void GridView1_RowEditing(object sender, GridViewEditEventArgs e)
        {
            GridView1.EditIndex = e.NewEditIndex;
            BindGridView();
        }

        protected void GridView1_RowUpdating(object sender, GridViewUpdateEventArgs e)
        {
            int id = Convert.ToInt32(GridView1.DataKeys[e.RowIndex].Value);
            GridViewRow row = GridView1.Rows[e.RowIndex];
            string skuName = (row.Cells[4].Controls[0] as TextBox).Text;
            string skuDescp = (row.Cells[5].Controls[0] as TextBox).Text;
            string skuOrientation = (row.Cells[6].Controls[0] as TextBox).Text;
            string skuDetails1 = (row.Cells[7].Controls[0] as TextBox).Text;
            string skuDetails2 = (row.Cells[8].Controls[0] as TextBox).Text;
            int viewMode = Convert.ToInt32((row.Cells[9].Controls[0] as TextBox).Text);

            string connString = ConfigurationManager.ConnectionStrings["DbConn"].ConnectionString;
            using (SqlConnection conn = new SqlConnection(connString))
            {
                using (SqlCommand cmd = new SqlCommand("UpdateBrandSKU", conn))
                {
                    cmd.CommandType = CommandType.StoredProcedure;
                    cmd.Parameters.AddWithValue("@Id", id);
                    cmd.Parameters.AddWithValue("@SKUName", skuName);
                    cmd.Parameters.AddWithValue("@SKUDescp", skuDescp);
                    cmd.Parameters.AddWithValue("@SKUOrientation", skuOrientation);
                    cmd.Parameters.AddWithValue("@SKUDetails1", skuDetails1);
                    cmd.Parameters.AddWithValue("@SKUDetails2", skuDetails2);
                    cmd.Parameters.AddWithValue("@ViewMode", viewMode);
                    conn.Open();
                    cmd.ExecuteNonQuery();
                    conn.Close();
                }
            }

            GridView1.EditIndex = -1;
            BindGridView();
        }

        protected void GridView1_RowCancelingEdit(object sender, GridViewCancelEditEventArgs e)
        {
            GridView1.EditIndex = -1;
            BindGridView();
        }

        protected void GridView1_RowDeleting(object sender, GridViewDeleteEventArgs e)
        {
            int id = Convert.ToInt32(GridView1.DataKeys[e.RowIndex].Values[0]);
            string connString = ConfigurationManager.ConnectionStrings["DbConn"].ConnectionString;
            using (SqlConnection conn = new SqlConnection(connString))
            {
                using (SqlCommand cmd = new SqlCommand("UPDATE MST_Brand_SKU set ViewMode=0 WHERE Id=@Id", conn))
                {
                    cmd.Parameters.AddWithValue("@Id", id);
                    conn.Open();
                    cmd.ExecuteNonQuery();
                    conn.Close();
                }
            }
            BindGridView();
        }

