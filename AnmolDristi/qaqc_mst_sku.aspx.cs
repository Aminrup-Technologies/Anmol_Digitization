        private void InsertDummyRecord(int brandId, string brandName, string skuName, string skuDescp, string skuOrientation, string skuDetails1, string skuDetails2)
        {
            string connString = ConfigurationManager.ConnectionStrings["DbConn"].ConnectionString;
            using (SqlConnection conn = new SqlConnection(connString))
            {
                using (SqlCommand cmd = new SqlCommand("InsertDummySKURecord", conn))
                {
                    cmd.CommandType = CommandType.StoredProcedure;
                    cmd.Parameters.AddWithValue("@BrandId", brandId);
                    cmd.Parameters.AddWithValue("@BrandName", brandName);
                    cmd.Parameters.AddWithValue("@SKUName", skuName);
                    cmd.Parameters.AddWithValue("@SKUDescp", skuDescp);
                    cmd.Parameters.AddWithValue("@SKUOrientation", skuOrientation);
                    cmd.Parameters.AddWithValue("@SKUDetails1", skuDetails1);
                    cmd.Parameters.AddWithValue("@SKUDetails2", skuDetails2);
                    cmd.Parameters.AddWithValue("@ViewMode", 1);
                    conn.Open();
                    cmd.ExecuteNonQuery();
                    conn.Close();
                }
            }
        }

